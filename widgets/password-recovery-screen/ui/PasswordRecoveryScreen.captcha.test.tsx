import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import type React from 'react';
import { beforeEach, expect, it, vi } from 'vitest';
import PasswordRecoveryScreen from './PasswordRecoveryScreen';
const mocks = vi.hoisted(() => ({ send: vi.fn(), reset: vi.fn() }));
vi.mock('next/image', () => ({ default: ({ alt }: { alt: string }) => <img alt={alt} /> }));
vi.mock('next/link', () => ({ default: ({ children, href }: { children: React.ReactNode; href: string }) => <a href={href}>{children}</a> }));
vi.mock('@/components/meta', () => ({ default: ({ children }: { children: React.ReactNode }) => <div>{children}</div> }));
vi.mock('@/features/auth/model/auth.store', () => ({ useAuthStore: (selector: (state: unknown) => unknown) => selector({ requestRecoveryCode: mocks.send, resetRecoveryPassword: mocks.reset }) }));
vi.mock('@/components/analytics', () => ({ log: vi.fn() }));
vi.mock('@/shared/ui/Font', () => ({ roboto: { variable: 'roboto-variable' } }));
vi.mock('@/shared/ui/YandexSmartCaptcha', () => ({ SMARTCAPTCHA_CLIENT_KEY: 'test-key', default: ({ onSuccess }: { onSuccess: (token: string) => void }) => <button type="button" onClick={() => onSuccess('token')}>CAPTCHA</button> }));
beforeEach(() => { vi.resetAllMocks(); mocks.send.mockResolvedValue({ st: true }); });
it('shows CAPTCHA on the request step only', async () => {
  render(<PasswordRecoveryScreen />);
  fireEvent.change(screen.getByLabelText('Номер телефона'), { target: { value: '79870001122' } });
  expect(screen.getByRole('button', { name: 'Получить код' })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: 'CAPTCHA' }));
  fireEvent.click(screen.getByRole('button', { name: 'Получить код' }));
  await waitFor(() => expect(mocks.send).toHaveBeenCalledWith('79870001122', 'sms', 'token'));
  expect(await screen.findByText('Введите код')).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'CAPTCHA' })).not.toBeInTheDocument();
});
